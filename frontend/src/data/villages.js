// Helper to format full display label
export function getVillageDisplayLabel(v) {
  if (v.label) return v.label;
  return `${v.name}, ${v.district}, ${v.state}`;
}

// Instant local search across verified villages
export function searchLocalVillages(rawQuery, limit = 8) {
  const query = (rawQuery || '').trim().toLowerCase();
  if (!query) {
    // Return top popular hubs as default suggestions
    return VERIFIED_VILLAGES.slice(0, limit).map((v) => ({
      ...v,
      label: getVillageDisplayLabel(v),
      source: 'verified',
    }));
  }

  // Exact startsWith first, then contains
  const startsWithMatches = [];
  const containsMatches = [];

  for (const v of VERIFIED_VILLAGES) {
    const nameLow = v.name.toLowerCase();
    const distLow = v.district.toLowerCase();
    const fullLow = `${nameLow} ${distLow} ${v.state.toLowerCase()}`;

    if (nameLow.startsWith(query)) {
      startsWithMatches.push({ ...v, label: getVillageDisplayLabel(v), source: 'verified' });
    } else if (fullLow.includes(query)) {
      containsMatches.push({ ...v, label: getVillageDisplayLabel(v), source: 'verified' });
    }
  }

  return [...startsWithMatches, ...containsMatches].slice(0, limit);
}

// Haversine distance in km
export function getDistanceKm(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

// Find nearest verified village for given coordinates
export function findNearestVillage(lat, lon, maxDistanceKm = 35) {
  let best = null;
  let minD = Infinity;
  for (const v of VERIFIED_VILLAGES) {
    const d = getDistanceKm(lat, lon, v.lat, v.lon);
    if (d < minD) {
      minD = d;
      best = v;
    }
  }
  if (best && minD <= maxDistanceKm) {
    return { ...best, distanceKm: Math.round(minD * 10) / 10, label: getVillageDisplayLabel(best) };
  }
  return null;
}

// Online OpenStreetMap Nominatim fallback with timeout
export async function searchOnlineVillages(query, limit = 5) {
  const q = (query || '').trim();
  if (!q || q.length < 2) return [];

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 3500);

  try {
    const url = `https://nominatim.openstreetmap.org/search?q=${encodeURIComponent(
      q
    )}&countrycodes=in&format=json&addressdetails=1&limit=${limit}`;
    const res = await fetch(url, {
      signal: controller.signal,
      headers: {
        Accept: 'application/json',
      },
    });
    clearTimeout(timer);
    if (!res.ok) return [];

    const data = await res.json();
    if (!Array.isArray(data)) return [];

    return data.map((item) => {
      const addr = item.address || {};
      const placeName =
        addr.village ||
        addr.town ||
        addr.hamlet ||
        addr.suburb ||
        addr.city ||
        addr.county ||
        item.name ||
        q;
      const district = addr.county || addr.state_district || addr.city || '';
      const state = addr.state || 'India';
      const cleanParts = [placeName, district, state].filter(Boolean);
      const label = item.display_name
        ? item.display_name.split(',').slice(0, 3).map((s) => s.trim()).join(', ')
        : cleanParts.join(', ');

      return {
        name: placeName,
        district,
        state,
        lat: Number(Number(item.lat).toFixed(5)),
        lon: Number(Number(item.lon).toFixed(5)),
        label,
        source: 'osm',
      };
    });
  } catch {
    clearTimeout(timer);
    return [];
  }
}

